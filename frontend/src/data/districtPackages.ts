// Helper to find district by any identifier or variation
export function findDistrictMeta(query: string): DistrictMeta | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();

  return NEPAL_DISTRICTS_REGISTRY.find((d) => {
    if (d.id === q) return true;
    if (d.name.toLowerCase() === q) return true;
    if (d.mapName.toLowerCase() === q) return true;
    // Common aliases
    if (q === 'everest' || q === 'khumbu') return d.id === 'solukhumbu';
    if (q === 'pokhara' || q === 'abc' || q === 'annapurna') return d.id === 'kaski';
    if (q === 'lo manthang') return d.id === 'mustang';
    if (q === 'tilicho') return d.id === 'manang';
    if (q === 'langtang') return d.id === 'rasuwa';
    if (q === 'rara') return d.id === 'mugu';
    if (q === 'patan') return d.id === 'lalitpur';
    return false;
  });
}

// Retrieve destination packages & hotels for a specific district
export function getDistrictPackages(districtName: string): {
  districtMeta: DistrictMeta;
  packages: Destination[];
  hotels: Hotel[];
  hasPackages: boolean;
} {
  const meta = findDistrictMeta(districtName) || NEPAL_DISTRICTS_REGISTRY[0];

  const matchedPackages = destinations.filter((pkg) => meta.packageIds.includes(pkg.id));
  const matchedHotels = hotels.filter((h) => meta.hotelIds.includes(h.id));

  return {
    districtMeta: meta,
    packages: matchedPackages,
    hotels: matchedHotels,
    hasPackages: matchedPackages.length > 0 || matchedHotels.length > 0,
  };
}

// Check if a district has listed packages
export function hasDistrictPackages(districtName: string): boolean {
  const meta = findDistrictMeta(districtName);
  if (!meta) return false;
  return meta.packageIds.length > 0 || meta.hotelIds.length > 0;
}

// Count total packages and lodges for a district
export function getDistrictTotalOfferings(districtName: string): number {
  const meta = findDistrictMeta(districtName);
  if (!meta) return 0;
  return meta.packageIds.length + meta.hotelIds.length;
}
